items = input("Enter 5 array values separated by commas: ").split(",")
items = [item.strip() for item in items]

print("\nOriginal List:", items)

index = int(input("Input Index to Update: "))
new_value = input("Input New Value: ")

print("Index to Update:", index)
print("New Value:", new_value)

items[index] = new_value

start = int(input("Enter Slice Range 1: "))
end = int(input("Enter Slice Range 2: "))

sliced_list = items[start:end]

print("Sliced List:", sliced_list)

search_item = input("Enter Search Item: ")

if search_item in sliced_list:
    print("Search Result:", search_item, "was found in the sliced list.")
else:
    print("Search Result:", search_item, "was not found in the sliced list.")

print("Updated List:", items)